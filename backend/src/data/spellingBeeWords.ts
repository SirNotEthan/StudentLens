const DICTIONARY_API_URL = "https://api.dictionaryapi.dev/api/v2/entries/en/";

export async function isValidSpellingBeeWord(word: string): Promise<boolean> {
  const upperWord = word.toUpperCase();
  const lowerWord = word.toLowerCase();

  if (VALID_SPELLING_BEE_WORDS.has(lowerWord)) {
    return true;
  }

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3000);

    const response = await fetch(`${DICTIONARY_API_URL}${lowerWord}`, {
      signal: controller.signal
    });

    clearTimeout(timeoutId);
    return response.status === 200;
  } catch (error) {
    console.error("Error checking word validity:", error);
    return false;
  }
}

export const getTodayDateString = (): string => {
  const date = new Date();
  return date.toISOString().split('T')[0];
};

export const getDailySpellingBeePuzzle = () => {
  const startDate = new Date('2025-01-01');
  const today = new Date();
  const daysDiff = Math.floor((today.getTime() - startDate.getTime()) / (1000 * 60 * 60 * 24));
  const puzzleIndex = daysDiff % SPELLING_BEE_PUZZLES.length;
  return SPELLING_BEE_PUZZLES[puzzleIndex];
};
